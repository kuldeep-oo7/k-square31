"use strict";
const assert = require("node:assert/strict");
const { evaluateSentimentAndEventRisk: evaluate } = require("../api/_lib/sentiment-risk");
const now = Date.parse("2026-09-17T05:00:00Z"), symbol = "TEST";
const coverage = Object.fromEntries(["events", "news", "foBan"].map(k => [k, { asOf: new Date(now - 1000).toISOString(), source: "TEST_FEED", verified: true, symbols: [symbol], completeThrough: "2026-10-15T00:00:00Z" }]));
const base = { now, symbol, events: [], newsHeadlines: [], foBanList: [], coverage };
assert.equal(evaluate({ symbol, now }).status, "UNKNOWN");
assert.equal(evaluate({ symbol, now }).allowedToTrade, false, "Missing calendar is not cleared");
assert.equal(evaluate(base).allowedToTrade, true);
assert.equal(evaluate(base).sentimentScore, null);
assert.equal(evaluate({ ...base, foBanList: [symbol] }).allowedToTrade, false);
assert.equal(evaluate({ ...base, assetClass: "CASH", foBanList: [symbol] }).allowedToTrade, true, "F&O ban does not ban cash delivery");
const event = { symbol, date: "2026-09-17", type: "EARNINGS", source: "EXCHANGE", publishedAt: "2026-09-16T05:00:00Z" };
assert.equal(evaluate({ ...base, events: [event] }).allowedToTrade, false, "Date-only events must not disappear after midnight");
assert.equal(evaluate({ ...base, events: [{ ...event, publishedAt: "2026-09-18T00:00:00Z" }] }).status, "UNKNOWN");
const news = { id: "N1", title: "fraud investigation", source: "EXCHANGE", symbols: [symbol], publishedAt: new Date(now - 1000).toISOString() };
assert.equal(evaluate({ ...base, newsHeadlines: [news] }).allowedToTrade, false);
assert.equal(evaluate({ ...base, newsHeadlines: [news, news] }).ignoredHeadlines, 1);
assert.equal(evaluate({ ...base, newsHeadlines: [{ ...news, symbols: ["OTHER"] }] }).sentimentScore, null);
assert.equal(evaluate({ ...base, newsHeadlines: [{ ...news, publishedAt: new Date(now + 1000).toISOString() }] }).ignoredHeadlines, 1);
assert.equal(evaluate({ ...base, coverage: { ...coverage, news: { ...coverage.news, asOf: "2020-01-01" } } }).allowedToTrade, false);
assert.equal(evaluate({ symbol: "", now }).allowedToTrade, false);
console.log("Sentiment tests passed: unknown coverage blocks, point-in-time/entity/dedup checks, date-only events, F&O versus cash scope.");
