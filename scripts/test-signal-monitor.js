"use strict";
const assert = require("node:assert/strict");
const { SignalMonitor } = require("../api/_lib/signal-monitor");
let now = Date.parse("2026-09-15T05:00:00Z");
const instruments = [{ key: "NSE:TEST", tradingSymbol: "TEST", type: "EQ", expiry: null }];
const monitor = new SignalMonitor({ instruments, clock: () => now });
const quote = (price, extra = {}) => ({ instrumentKey: "NSE:TEST", lastPrice: price, eventAt: now, provider: "TEST_FIXTURE", timestampKind: "EXCHANGE", marketOpen: true, session: "2026-09-15",
  priorSession: { date: "2026-09-14", availableAt: now - 86400000, sourceVerified: true, high: 110, low: 90 }, ...extra });
assert.equal(monitor.status().state, "WAITING_FOR_VERIFIED_FEED");
assert.equal(monitor.consume(quote(109)).alerts.length, 0, "first quote primes rather than inventing a crossing");
now += 1000;
const crossed = monitor.consume(quote(111));
assert.equal(crossed.alerts[0].kind, "PRIOR_HIGH_BREAKOUT");
assert.equal(crossed.alerts[0].actionable, false);
assert.equal(crossed.alerts[0].confidenceProbability, null);
assert.equal(monitor.consume(quote(111)).reason, "DUPLICATE_OR_OUT_OF_ORDER");
now += 1000; assert.equal(monitor.consume(quote(112)).alerts.length, 0);
now += 1000; monitor.consume(quote(109));
now += 1000; assert.equal(monitor.consume(quote(111)).alerts.length, 0, "cooldown deduplicates repeated crosses");
const restored = new SignalMonitor({ instruments, clock: () => now, restored: monitor.snapshot() });
restored.consume(quote(109)); now += 1000;
assert.equal(restored.consume(quote(111)).alerts.length, 0, "restart preserves cooldown");
assert.equal(monitor.consume(quote(111, { eventAt: now - 6000 })).reason, "STALE_OR_UNVERIFIED_QUOTE");
assert.equal(monitor.consume(quote(111, { timestampKind: "RECEIVED" })).reason, "STALE_OR_UNVERIFIED_QUOTE");
assert.equal(monitor.consume(quote(111, { instrumentKey: "NSE:UNKNOWN" })).reason, "UNKNOWN_INSTRUMENT");
assert.equal(monitor.consume(quote(111, { marketOpen: false })).reason, "MARKET_CLOSED_OR_SESSION_UNVERIFIED");
now += 11000; assert.equal(monitor.status().state, "FEED_STALE");
assert.equal(monitor.consume(quote(80)).alerts.length, 0, "do not reconstruct a crossing after a missing-feed gap");
now = Date.parse("2026-09-15T15:00:00Z");
assert.equal(monitor.consume(quote(100)).reason, "OUTSIDE_NORMAL_CASH_DERIVATIVES_SESSION");
console.log("Signal monitor tests passed: event-driven crossing, no first-tick guess, freshness, session/identity guards, restart dedupe, gap abstention and no certainty/order claims.");
